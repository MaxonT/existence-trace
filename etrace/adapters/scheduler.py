"""Scheduler adapters: turn [tasks] in trace.toml into files for an agent runner.

    codex        one automation.toml per task (kind = "cron", RRULE + timezone)
    claude-code  one shell script per task that runs `claude -p` with the prompt
    cron         one crontab snippet (CRON_TZ + a line per task time)

write() only writes files into the output directory. It never installs
anything: no crontab, no LaunchAgent, nothing under the agent's own config.
Every generated run renders its prompt at run time with
`python3 -m etrace prompt TASK --raw`, so new rules reach the agent without
regenerating the files.
"""

import os
import shlex

from etrace import config
from etrace.store import write_text_atomic

TARGETS = ("codex", "claude-code", "cron")
_RRULE_DAYS = {"Mon": "MO", "Tue": "TU", "Wed": "WE", "Thu": "TH", "Fri": "FR", "Sat": "SA", "Sun": "SU"}
_CRON_DAYS = {"Mon": 1, "Tue": 2, "Wed": 3, "Thu": 4, "Fri": 5, "Sat": 6, "Sun": 0}
_CODEX_PROMPT = {
    "zh": ("existence-trace 的 {task} 任务。先运行下面的命令，然后严格按它打印的说明执行。"
           "之后每条 `python3 -m etrace` 命令都在同一个 shell 里运行，或者先重复这段 cd/export：\n\n{command}\n"),
    "en": ("existence-trace task {task}. Run the command below, then follow the instructions it prints exactly. "
           "Run every later `python3 -m etrace` command in the same shell, or repeat the cd/export part first:"
           "\n\n{command}\n"),
}


class SchedulerError(ValueError):
    """Unknown target or an unusable output directory."""


def parse_time(value):
    """'HH:MM' or 'Ddd HH:MM' -> (weekday or None, hour, minute)."""
    day, _, hhmm = value.rpartition(" ")
    hour, minute = hhmm.split(":")
    return (day or None), int(hour), int(minute)


def schedule(cfg):
    """{task: [(weekday or None, hour, minute), ...]} from the config, in TASKS order."""
    return {task: [parse_time(t) for t in cfg.tasks[task]] for task in config.TASKS}


def _package_parent():
    """Directory that holds the etrace package, for PYTHONPATH."""
    return os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def env_command(cfg):
    """`cd ROOT && export ...`: the environment every etrace command of a run needs.

    It is exported (not a one-command prefix) so the agent started afterwards
    finds the same config and package when it runs `python3 -m etrace ...`.
    """
    q = shlex.quote
    config_path = cfg.source or os.path.join(cfg.data_dir, "trace.toml")
    return (f"cd {q(cfg.data_dir)} && export ETRACE_CONFIG={q(config_path)} "
            f"PYTHONPATH={q(_package_parent())}")


def prompt_command(cfg, task):
    """Shell command that sets the environment and prints the rendered prompt for TASK."""
    return f"{env_command(cfg)} && python3 -m etrace prompt {task} --raw"


# --- codex -----------------------------------------------------------------------

def rrules(times):
    """RRULE strings covering every time; times sharing a weekday and a minute share one rule."""
    groups = {}
    for day, hour, minute in times:
        groups.setdefault((day, minute), []).append(hour)
    out = []
    for (day, minute), hours in groups.items():
        parts = ["FREQ=WEEKLY", f"BYDAY={_RRULE_DAYS[day]}"] if day else ["FREQ=DAILY"]
        parts += [f"BYHOUR={','.join(str(h) for h in sorted(hours))}", f"BYMINUTE={minute}"]
        out.append(";".join(parts))
    return out


def _toml_str(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def codex_files(cfg):
    """{filename: text}: one automation.toml per task (per rule, if one RRULE cannot cover all times)."""
    files = {}
    for task, times in schedule(cfg).items():
        rules = rrules(times)
        for i, rule in enumerate(rules, 1):
            suffix = f"-{i}" if len(rules) > 1 else ""
            name = f"etrace-{task}{suffix}"
            prompt = _CODEX_PROMPT[cfg.language].format(task=task, command=prompt_command(cfg, task))
            files[os.path.join(name, "automation.toml")] = "\n".join([
                "# Generated by `python3 -m etrace schedule --target codex`. Not installed.",
                f"id = {_toml_str(name)}",
                f"name = {_toml_str(name)}",
                'kind = "cron"',
                f"rrule = {_toml_str(rule)}",
                f"timezone = {_toml_str(cfg.timezone)}",
                f"cwd = {_toml_str(cfg.data_dir)}",
                f"prompt = {_toml_str(prompt)}",
                'status = "ACTIVE"',
                "",
            ])
    return files


# --- claude code -----------------------------------------------------------------

def _hhmm(day, hour, minute):
    return f"{day + ' ' if day else ''}{hour:02d}:{minute:02d}"


def claude_code_files(cfg):
    """{filename: text}: etrace-TASK.sh per task, its schedule in the header."""
    files = {}
    for task, times in schedule(cfg).items():
        when = ", ".join(_hhmm(*t) for t in times)
        files[f"etrace-{task}.sh"] = "\n".join([
            "#!/bin/sh",
            "# Generated by `python3 -m etrace schedule --target claude-code`. Not installed.",
            f"# task: {task}",
            f"# schedule: {when}",
            f"# timezone: {cfg.timezone}",
            "# Run it from your own scheduler at those times. CLAUDE and ETRACE_CLAUDE_FLAGS",
            "# override the claude binary and its flags (e.g. allowed tools).",
            "set -eu",
            env_command(cfg),
            f"PROMPT=$(python3 -m etrace prompt {task} --raw)",
            '"${CLAUDE:-claude}" -p ${ETRACE_CLAUDE_FLAGS:-} "$PROMPT"',
            "",
        ])
    return files


# --- cron ------------------------------------------------------------------------

def cron_lines(cfg):
    """Crontab lines, one per task time; each pipes the prompt into `claude -p`.

    cron treats an unescaped % as a newline, so it is escaped in the command.
    """
    lines = []
    for task, times in schedule(cfg).items():
        for day, hour, minute in times:
            dow = _CRON_DAYS[day] if day else "*"
            command = f"{prompt_command(cfg, task)} | claude -p".replace("%", "\\%")
            lines.append(f"{minute} {hour} * * {dow} {command}  # etrace {task}")
    return lines


def cron_files(cfg):
    text = "\n".join([
        "# Generated by `python3 -m etrace schedule --target cron`. Not installed.",
        "# Review it, then add it yourself with `crontab -e`.",
        f"# Times are in {cfg.timezone}. CRON_TZ works with cronie/Vixie cron; if your cron",
        "# ignores it, convert the times to the machine's local zone.",
        f"CRON_TZ={cfg.timezone}",
        *cron_lines(cfg),
        "",
    ])
    return {"etrace.crontab": text}


_RENDER = {"codex": codex_files, "claude-code": claude_code_files, "cron": cron_files}


def render(target, cfg):
    if target not in TARGETS:
        raise SchedulerError(f"target: must be one of {', '.join(TARGETS)}, got {target!r}")
    return _RENDER[target](cfg)


def write(target, cfg, out_dir):
    """Write the target's files under out_dir and return their paths. Installs nothing."""
    files = render(target, cfg)
    out_dir = os.path.abspath(os.path.expanduser(out_dir))
    if os.path.exists(out_dir) and not os.path.isdir(out_dir):
        raise SchedulerError(f"out: {out_dir} is not a directory")
    written = []
    for name, text in files.items():
        path = os.path.join(out_dir, name)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        write_text_atomic(path, text)
        if name.endswith(".sh"):
            os.chmod(path, 0o755)
        written.append(path)
    return written
